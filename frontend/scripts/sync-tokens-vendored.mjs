// Aurora Launch — regenerate tokens.vendored.json from the design-system SSOT.
//
// #51 (shared-lib audit Sprint 0 follow-up). `tokens.vendored.json` — это
// производный артефакт: CI-only зеркало `06_Aurora_Design_system/01_Tokens/
// tokens.json` (SSOT). Запускай эту команду при любом изменении SSOT, затем
// коммить результат. `npm run check:tokens` (pre-commit) держит их в синхроне.
//
// Output форматируется через локальный prettier (.prettierrc) — vendored всегда
// prettier-clean, без трения с pre-commit prettier-хуком.
//
// Run: `npm run sync:tokens`.

import { promises as fs } from 'node:fs';
import prettier from 'prettier';
import { SSOT_PATH, VENDORED_PATH, VENDORED_ANNOTATION_KEY } from './check-tokens-vendored.mjs';

const ANNOTATION =
  'Mirror of 06_Aurora_Design_system/01_Tokens/tokens.json (CI-only fallback). ' +
  'Generated by `npm run sync:tokens` — do NOT hand-edit; `npm run check:tokens` enforces sync.';

async function main() {
  let ssotRaw;
  try {
    ssotRaw = await fs.readFile(SSOT_PATH, 'utf-8');
  } catch (e) {
    if (e.code === 'ENOENT') {
      console.error(`[sync:tokens] SSOT not found at ${SSOT_PATH}.`);
      console.error(
        '[sync:tokens] Run this on a machine with the 06_Aurora_Design_system sibling directory.'
      );
      process.exit(2);
    }
    throw e;
  }

  const ssot = JSON.parse(ssotRaw);
  // Inject the self-documenting vendored annotation into $metadata (stripped by
  // check:tokens before comparing, so it never counts as drift).
  ssot.$metadata = ssot.$metadata ?? {};
  ssot.$metadata[VENDORED_ANNOTATION_KEY] = ANNOTATION;

  const prettierConfig = (await prettier.resolveConfig(VENDORED_PATH)) ?? {};
  const formatted = await prettier.format(JSON.stringify(ssot), {
    ...prettierConfig,
    parser: 'json',
    filepath: VENDORED_PATH,
  });

  await fs.writeFile(VENDORED_PATH, formatted, 'utf-8');
  console.log(`[sync:tokens] Regenerated ${VENDORED_PATH} from SSOT.`);
}

main().catch((e) => {
  console.error('[sync:tokens] failed:', e);
  process.exit(1);
});
